import 'dart:async';
import 'dart:convert';
import 'dart:io';

/// YouTube 登入 cookie 的匯出與檢查。
///
/// ## 核心設計：身分留在瀏覽器裡
///
/// 不去硬解使用者主瀏覽器的 cookie 檔（Chrome 127+ 的 App-Bound
/// Encryption 解不開，而且 2026-10-17 實測：拿主 profile 複製/啟動 +
/// 強制關閉 Chrome，會打斷使用者自己的登入工作階段）。
///
/// 改成**專用 profile**：
///   1. 程式用自己的 `--user-data-dir` 啟動一個獨立 Chrome（不碰主 profile）
///   2. 導到 Google 登入頁，使用者在**那個視窗**登入 YouTube（只做一次）
///   3. 透過 DevTools Protocol（瀏覽器自己的介面）請它交出 cookie
///   4. 之後每次都是全自動，不需要再登入、也不需要擴充
///
/// ## 為什麼 CDP 這條路能通
///
/// Chrome 136+ 只禁止 `--remote-debugging-port` 搭配**預設**使用者資料
/// 目錄；用我們自己的目錄就不受限制（實測 Chrome 155 handshake 成功）。
/// 而 CDP 執行在瀏覽器行程內部，所以 App-Bound 加密由瀏覽器自己解，
/// 外部程式不需要（也不應該）碰金鑰。
///
/// ## 絕不影響使用者日常瀏覽器
///
/// - 使用獨立 profile 目錄
/// - 只關閉**自己啟動**的那個行程（記 PID），絕不 taskkill 整個 chrome.exe
class CookieExport {
  CookieExport._();

  static const _authCookies = {
    'LOGIN_INFO', 'SAPISID', 'APISID', 'SID', 'HSID', 'SSID', 'SIDCC',
    '__Secure-1PSID', '__Secure-3PSID',
    '__Secure-1PAPISID', '__Secure-3PAPISID',
    '__Secure-1PSIDTS', '__Secure-3PSIDTS',
  };

  /// 登入 cookie 的完整清單長度（顯示分母用，別寫死）。
  static int get authCookieCount => _authCookies.length;

  static const _port = 9222;
  static const _loginUrl =
      'https://accounts.google.com/ServiceLogin?service=youtube&continue=https://www.youtube.com';

  // ── 路徑 ───────────────────────────────────────────

  /// 現有 cookie 檔（依序找）。
  static String? existingCookiePath() {
    final home = Platform.environment['USERPROFILE'] ?? '';
    if (home.isEmpty) return null;
    for (final p in [
      '$home\\Desktop\\yt_cookies.txt',
      '$home\\Downloads\\yt_cookies.txt',
    ]) {
      if (File(p).existsSync()) return p;
    }
    return null;
  }

  static String defaultOutPath() =>
      existingCookiePath() ??
      '${Platform.environment['USERPROFILE'] ?? ''}\\Desktop\\yt_cookies.txt';

  /// 專用 profile 目錄：跟主 profile 完全隔離。
  static String dedicatedProfilePath(String basePath) {
    final sep = Platform.pathSeparator;
    final dir = '$basePath${sep}cache${sep}chrome-cookie-profile';
    if (!Directory(dir).existsSync()) {
      Directory(dir).createSync(recursive: true);
    }
    return dir;
  }

  // ── 檢查 ───────────────────────────────────────────

  /// 讀 cookie 檔，回報是否具備登入身分。
  ///
  /// `generatedByYtDlp` 辨識「這個檔是 yt-dlp 寫的」——那種情況下
  /// 登入 cookie **一定會缺**，因為 yt-dlp 解不開 Chrome 的加密區塊，
  /// 只能匯出 PREF / YSC 這類未加密 cookie。檔案格式正常、也有內容，
  /// 卻靜靜地少了登入身分（2026-10-17 實測踩過）。
  static ({int total, int auth, List<String> missing, String? path,
      bool generatedByYtDlp}) inspect([String? path]) {
    final p = path ?? existingCookiePath();
    if (p == null || !File(p).existsSync()) {
      return (
        total: 0, auth: 0, missing: _authCookies.toList(),
        path: null, generatedByYtDlp: false
      );
    }
    final names = <String>{};
    var fromYtDlp = false;
    try {
      for (var line in File(p).readAsLinesSync()) {
        // Netscape 格式的 HttpOnly cookie，網域欄位帶 `#HttpOnly_` 前綴，
        // **整行以 # 開頭但不是註解**。舊版一律當註解跳過 → 實測匯出
        // 77 個 cookie 只數到 7 個，連帶低估登入 cookie 數量。
        if (line.startsWith('#HttpOnly_')) {
          line = line.substring('#HttpOnly_'.length);
        } else if (line.startsWith('#')) {
          if (line.contains('generated by yt-dlp')) fromYtDlp = true;
          continue;
        }
        if (line.trim().isEmpty) continue;
        final f = line.split('\t');
        if (f.length >= 7) names.add(f[5]);
      }
    } catch (_) {
      return (
        total: 0, auth: 0, missing: _authCookies.toList(),
        path: p, generatedByYtDlp: false
      );
    }
    return (
      total: names.length,
      auth: names.where(_authCookies.contains).length,
      missing: _authCookies.difference(names).toList(),
      path: p,
      generatedByYtDlp: fromYtDlp
    );
  }

  // ── Chrome ─────────────────────────────────────────

  static String? _chromeExe() {
    final la = Platform.environment['LOCALAPPDATA'] ?? '';
    final pf = Platform.environment['ProgramFiles'] ?? 'C:\\Program Files';
    final pf86 = Platform.environment['ProgramFiles(x86)'] ?? '';
    for (final c in [
      if (la.isNotEmpty) '$la\\Google\\Chrome\\Application\\chrome.exe',
      if (pf.isNotEmpty) '$pf\\Google\\Chrome\\Application\\chrome.exe',
      if (pf86.isNotEmpty) '$pf86\\Google\\Chrome\\Application\\chrome.exe',
    ]) {
      if (File(c).existsSync()) return c;
    }
    return null;
  }

  /// 用**專用 profile** 啟動 Chrome，開登入頁。回傳行程 ID。
  ///
  /// 注意：不要加 `--new-window`（Chrome 會把它當成開關而忽略整組參數），
  /// 也不要用預設 profile（Chrome 136+ 會忽略 debug 埠）。
  static Future<int?> launchLoginWindow(String profileDir) async {
    final exe = _chromeExe();
    if (exe == null) return null;
    final p = await Process.start(exe, [
      '--remote-debugging-port=$_port',
      '--remote-allow-origins=*',
      '--user-data-dir=$profileDir',
      '--no-first-run',
      '--no-default-browser-check',
      _loginUrl,
    ], mode: ProcessStartMode.detached, runInShell: false);
    return p.pid;
  }

  /// 只關閉我們自己啟動的那個 Chrome 行程樹（絕不 taskkill 全部 chrome.exe）。
  static Future<void> closeOwned(int pid) async {
    if (pid <= 0) return;
    // Chrome 的子行程共用同一個 user-data-dir；用 taskkill /T 只殺這棵樹
    try {
      await Process.run('taskkill', ['/pid', '$pid', '/T', '/F'],
          runInShell: true);
    } catch (_) {}
  }

  static Future<bool> cdpAlive() async {
    try {
      final c = HttpClient();
      final r = await c
          .getUrl(Uri.parse('http://127.0.0.1:$_port/json/version'))
          .timeout(const Duration(seconds: 3));
      await r.close();
      c.close();
      return true;
    } catch (_) {
      return false;
    }
  }

  /// 透過 CDP 取 cookie。回傳 (cookie 名稱集合, 錯誤訊息)。
  static Future<(Set<String> names, String? error)> _fetchCookies() async {
    try {
      final c = HttpClient();
      final req = await c
          .getUrl(Uri.parse('http://127.0.0.1:$_port/json'))
          .timeout(const Duration(seconds: 10));
      final resp = await req.close();
      final body = await resp.transform(utf8.decoder).join();
      c.close();

      final targets = jsonDecode(body) as List<dynamic>;
      String? ws;
      for (final t in targets) {
        final m = t as Map<String, dynamic>;
        if ((m['type'] as String?) == 'page' &&
            m['webSocketDebuggerUrl'] != null &&
            ws == null) {
          ws = m['webSocketDebuggerUrl'] as String;
        }
      }
      if (ws == null) return (<String>{}, 'CDP 找不到可用的分頁');

      final sock = await WebSocket.connect(ws).timeout(
          const Duration(seconds: 10));
      final got = sock.first.timeout(const Duration(seconds: 20));
      sock.add(jsonEncode({
        'id': 1,
        'method': 'Storage.getCookies',
        'params': <String, dynamic>{},
      }));
      final msg = await got;
      await sock.close();

      final j = jsonDecode(msg as String) as Map<String, dynamic>;
      final res = (j['result'] as Map<String, dynamic>?) ?? {};
      final all = (res['cookies'] as List<dynamic>? ?? []);
      final names = <String>{};
      final yt = <Map<String, dynamic>>[];
      for (final e in all) {
        final m = e as Map<String, dynamic>;
        final d = (m['domain'] as String?) ?? '';
        if (d.contains('youtube.com') || d.contains('google.com')) {
          names.add((m['name'] as String?) ?? '');
          yt.add(m);
        }
      }
      _lastCookies = yt;
      return (names, null);
    } catch (e) {
      return (<String>{}, 'CDP 取 cookie 失敗: $e');
    }
  }

  static List<Map<String, dynamic>> _lastCookies = [];

  /// 完整流程：開登入視窗 → 等使用者登入 → 寫 cookie 檔 → 關掉自己開的視窗。
  ///
  /// [basePath] 用來放專用 profile；[onStatus] 回報給 UI/CLI 顯示。
  static Future<(bool ok, String message)> interactiveExport({
    required String basePath,
    String? outPath,
    Duration loginTimeout = const Duration(minutes: 5),
    void Function(String)? onStatus,
  }) async {
    final target = outPath ?? defaultOutPath();
    final profile = dedicatedProfilePath(basePath);
    final backup = '$target.bak';

    onStatus?.call('啟動專用 Chrome（不影響你平常的瀏覽器）…');
    final pid = await launchLoginWindow(profile);
    if (pid == null) {
      return (false, '找不到 Chrome 執行檔');
    }

    try {
      // 等 CDP 起來
      var ready = false;
      for (var i = 0; i < 25; i++) {
        await Future<void>.delayed(const Duration(seconds: 1));
        if (await cdpAlive()) {
          ready = true;
          break;
        }
      }
      if (!ready) {
        return (false, 'Chrome 啟動了但除錯埠沒有綁定（:$_port）');
      }

      // 等使用者完成登入：每 3 秒問一次有沒有登入 cookie
      onStatus?.call('請在剛開的那個 Chrome 視窗登入 Google 帳號');
      onStatus?.call('（只需做一次；之後每次都會自動取得）');
      final deadline = DateTime.now().add(loginTimeout);
      Set<String> names = <String>{};
      while (DateTime.now().isBefore(deadline)) {
        final (n, err) = await _fetchCookies();
        if (err == null) {
          names = n;
          if (names.any(_authCookies.contains)) break;
        }
        await Future<void>.delayed(const Duration(seconds: 3));
      }

      final auth = names.where(_authCookies.contains).toSet();
      if (auth.isEmpty) {
        onStatus?.call('（等不到登入狀態）');
        return (
          false,
          '在時限內沒有偵測到登入狀態。\n'
              '請確認那個 Chrome 視窗裡 YouTube 右上角已顯示頭像。\n'
              '（偵測到的 cookie：${names.isEmpty ? "無" : names.take(8).join(", ")}）'
        );
      }

      onStatus?.call('偵測到登入狀態（${auth.length} 個登入 cookie）');
      final f = File(target);
      if (f.existsSync()) {
        try {
          f.copySync(backup);
        } catch (_) {}
      }
      f.writeAsStringSync(_toNetscape(_lastCookies));
      final r = inspect(target);
      return (
        true,
        '已匯出 ${r.total} 個 cookie，其中 ${r.auth} 個登入 cookie ✅\n'
            '檔案: $target'
            '${File(backup).existsSync() ? "\n備份: $backup" : ""}'
      );
    } finally {
      // 只關自己開的那棵行程樹
      await closeOwned(pid);
    }
  }

  static String _toNetscape(List<Map<String, dynamic>> cookies) {
    final sb = StringBuffer()
      ..writeln('# Netscape HTTP Cookie File')
      ..writeln('# 由 playlist-admin cookie export 經 Chrome DevTools Protocol 匯出')
      ..writeln('# 時間: ${DateTime.now().toIso8601String()}')
      ..writeln('# 來源: playlist-admin 專用 profile（不影響日常瀏覽器）');
    for (final m in cookies) {
      final domain = (m['domain'] as String?) ?? '.youtube.com';
      final path = (m['path'] as String?) ?? '/';
      final secure = (m['secure'] as bool?) ?? false;
      final httpOnly = (m['httpOnly'] as bool?) ?? false;
      final expires = (m['expires'] as num?)?.toDouble() ?? -1;
      final name = (m['name'] as String?) ?? '';
      final value = (m['value'] as String?) ?? '';
      final d = httpOnly ? '#HttpOnly_$domain' : domain;
      sb.writeln([
        d,
        domain.startsWith('.') ? 'TRUE' : 'FALSE',
        path,
        secure ? 'TRUE' : 'FALSE',
        expires < 0 ? 0 : expires.round(),
        name,
        value,
      ].join('\t'));
    }
    return sb.toString();
  }
}